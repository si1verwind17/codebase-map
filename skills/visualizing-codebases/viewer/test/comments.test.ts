import { describe, expect, it } from "vitest";
import shop from "./fixtures/shop.code-map.json";
import { Comments, EXPORT_HEADER, EXPORT_NAME } from "../src/comments/comments";
import { Model } from "../src/model/model";
import type { CodeMap } from "../src/model/types";

const map = shop as unknown as CodeMap;

function memoryStore() {
  const data = new Map<string, string>();
  return { getItem: (k: string) => data.get(k) ?? null, setItem: (k: string, v: string) => void data.set(k, v) };
}

describe("comments", () => {
  it("files a comment on a twin under the real package, never as orphaned", () => {
    const twinned = structuredClone(map);
    twinned.nodes.find((n) => n.id === "svc:shop")!.twins = ["worker::worker/"];
    twinned.layout.containers["svc:shop"].items["twin:worker::worker/"] = { region: "line", col: 5, row: 0 };
    const c = new Comments(new Model(twinned), memoryStore());
    c.add("twin:worker::worker/", "Why is this in shop too?");
    expect(c.orphaned()).toEqual([]);
    expect(c.all()[0].target).toBe("worker::worker/");
    expect(c.for("twin:worker::worker/")).toHaveLength(1);
  });

  it("ignores stored comments that are not a list", () => {
    const store = memoryStore();
    const model = new Model(map);
    store.setItem(`viz-code:comments:${map.meta.repo}`, '{"oops": 1}');
    const c = new Comments(model, store);
    expect(c.all()).toEqual([]);
    expect(c.orphaned()).toEqual([]);
  });

  it("treats a line to a door as the line to the door's anchor, and deletes one note", () => {
    const model = new Model(map);
    const c = new Comments(model, memoryStore());
    c.add("door:svc:shop|svc:worker", "Retry here?");
    c.add("svc:worker", "Rename run.");
    expect(c.orphaned()).toEqual([]);
    expect(c.for("door:svc:shop|svc:worker")).toHaveLength(1);
    const md = c.toMarkdown();
    expect(md).not.toContain("orphaned");
    expect(md).not.toContain("door:");
    c.drop(c.for("svc:worker")[0]);
    expect(c.all().map((x) => x.text)).toEqual(["Retry here?"]);
  });

  it("persist per repo and export markdown an agent can act on", () => {
    const model = new Model(map);
    const store = memoryStore();
    const c = new Comments(model, store);
    c.add("shop::io.demo.shop.repo.PgOrderRepo#save/2", "Publish after the commit, not before.", new Date("2026-10-04T10:00:00Z"));
    c.add("svc:shop|svc:worker", "Why is this inferred? Pin SHOP_URL in compose.");
    c.add("svc:worker", "   ");
    expect(new Comments(model, store).all()).toHaveLength(2);
    const md = c.toMarkdown();
    expect(EXPORT_NAME).toBe("export-comment.md");
    expect(md.startsWith(EXPORT_HEADER + "\n\n# Review comments")).toBe(true);
    expect(EXPORT_HEADER).toBe("<!-- Generated by the visualizing-codebases skill (the viewer, by you); review comments and pin changes exported from the viewer, for the agent to read. Do not edit: the next run overwrites it. -->");
    expect(md).toContain(`# Review comments — ${map.meta.repo} @ ${map.meta.commit.slice(0, 12)}`);
    expect(md).toContain(`git -C REPO show ${map.meta.commit.slice(0, 12)}:./<path>`);
    expect(md).toContain("`shop::io.demo.shop.repo.PgOrderRepo#save/2`");
    expect(md).toContain("shop/src/main/scala/io/demo/shop/repo/OrderRepo.scala:");
    expect(md).toContain("Publish after the commit, not before.");
    expect(md).toMatch(/### worker \(S\d\) ↔ shop \(S\d\)|### shop \(S\d\) ↔ worker \(S\d\)/);
  });

  it("flags comments whose node vanished after a rescan", () => {
    const model = new Model(map);
    const store = memoryStore();
    store.setItem(`viz-code:comments:${map.meta.repo}`, JSON.stringify([{ target: "svc:gone", text: "x", at: "t" }]));
    const c = new Comments(model, store);
    expect(c.orphaned()).toHaveLength(1);
    expect(c.toMarkdown()).toContain("**orphaned**");
  });

  it("survives broken storage", () => {
    const model = new Model(map);
    const bad = { getItem: () => "{not json", setItem: () => { throw new Error("quota"); } };
    const c = new Comments(model, bad);
    expect(() => c.add("svc:worker", "ok")).not.toThrow();
    expect(c.all()).toHaveLength(1);
  });
});
