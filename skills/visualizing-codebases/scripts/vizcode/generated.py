"""Generated and vendored files, by one rule for every language.

A file is generated when one of its first lines carries a generator's standard marker (`Code generated … DO NOT
EDIT`, `@generated`, `<auto-generated>`, `Generated by the protocol buffer compiler`, `@javax.annotation.Generated`)
or its name is a protoc output name (`*.pb.go`, `*_pb2.py`, …). The map keeps what the code around it needs from
it: its data types (public classes with their public fields), the routes it registers and their handlers. Every other class, method,
call and string goes.

A file is a vendored bundle when it is JavaScript and most of it sits on very long lines (minified). Such a file is
someone else's code, and is excluded like a vendored folder.
"""
from __future__ import annotations

import fnmatch
import re
from pathlib import Path

from .adapters import python as py_adapter
from .adapters.langs import SPECS

HEADER_LINES = 40
MARKER = re.compile(r"(?i)\bgenerated\b.*\bdo not edit\b|\bdo not edit\b.*\bgenerated\b|@generated\b|<auto-generated\b"
                    r"|\bgenerated by the protocol buffer compiler\b|@javax\.annotation\.(?:processing\.)?Generated\b")
NAMES = ["*.pb.go", "*_pb2.py", "*_pb2_grpc.py", "*_pb.ts", "*_pb.js", "*_grpc_pb.ts", "*_grpc_pb.js", "*.g.cs"]
BUNDLE_SUFFIXES = (".js", ".mjs", ".cjs")
LONG_LINE = 1000
# the facts of a file that name the node they sit in (`in`): kept only inside a kept node
INNER_FACTS = ("calls", "strings", "env_keys", "tables", "queues", "clients")


def generated(path: str, text: str) -> bool:
    name = path.rsplit("/", 1)[-1]
    if any(fnmatch.fnmatch(name, p) for p in NAMES):
        return True
    return any(MARKER.search(line) for line in text.split("\n", HEADER_LINES)[:HEADER_LINES])


def bundle(path: str, file: Path) -> bool:
    """A minified JavaScript file: more than half its bytes on lines over LONG_LINE characters."""
    if not path.endswith(BUNDLE_SUFFIXES):
        return False
    data = file.read_bytes()
    return sum(len(line) for line in data.split(b"\n") if len(line) > LONG_LINE) * 2 > len(data)


def _public_field(lang: str, field: dict) -> bool:
    """A field its modifiers (the field's `visibility`) or the language's naming (Go upper case, Python no leading
    underscore) make public."""
    if "visibility" in field:
        return field["visibility"] == "public"
    if lang == "python":
        return py_adapter._visibility(field["name"]) == "public"
    spec = SPECS.get(lang)
    return not (spec and spec.upper_exported) or field["name"][:1].isupper()


def keep_needed(r: dict, handlers: set[str], lang: str) -> None:
    """Reduce a generated file's parse result to its public data types with their public fields (a generator's own
    bookkeeping fields go), its routes and their handlers (with the nodes around them), and the facts inside what is
    kept."""
    for n in r["nodes"]:
        if n.get("fields"):
            n["fields"] = [f for f in n["fields"] if _public_field(lang, f)]
            if not n["fields"]:
                del n["fields"]
    by_id = {n["id"]: n for n in r["nodes"]}
    kept: set[str] = set()
    for n in r["nodes"]:
        if n["id"] in handlers or (n["kind"] == "class" and n.get("fields") and n["visibility"] == "public"):
            nid = n["id"]
            while nid in by_id and nid not in kept:
                kept.add(nid)
                nid = by_id[nid]["parent"]
    r["nodes"] = [n for n in r["nodes"] if n["id"] in kept]
    for n in r["nodes"]:
        if n["kind"] == "class" and "methods" in n["metrics"]:
            n["metrics"]["methods"] = sum(1 for m in r["nodes"] if m["kind"] == "method" and m["parent"] == n["id"])
    for key in INNER_FACTS:
        if key in r:
            r[key] = [x for x in r[key] if x.get("in") in kept]
    for key in ("supers", "bases"):
        if key in r:
            r[key] = [(cid, b) for cid, b in r[key] if cid in kept]
    r["attached"] = []
