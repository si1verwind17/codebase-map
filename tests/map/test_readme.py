import json
import subprocess

import assemble as assemble_cli
import extract
from meaning_fixture import MEANING
from vizcode.map import assemble as vassemble
from vizcode import readme


def build(repo):
    extract.main([str(repo)])
    out = repo / "docs" / "viz-code"
    (out / "meaning.json").write_text(json.dumps(MEANING))
    assert assemble_cli.main([str(repo)]) == 0
    return out


def test_readme_written_and_committed(shop_repo):
    out = build(shop_repo)
    text = (out / "README.md").read_text()
    assert text.startswith("# viz-code\n")
    assert "generated by the visualizing-codebases skill" in text and "run the skill again" in text
    r = subprocess.run(["git", "check-ignore", "-q", "docs/viz-code/README.md"], cwd=shop_repo)
    assert r.returncode == 1


def test_readme_rows_cover_gitignore():
    rows = {f: committed for f, _, _, committed in readme.FILES}
    for name in vassemble.GITIGNORE:
        assert rows.get(name) is False, name
    committed = {"code-map.json", "stack.yaml", "map-notes.md", "README.md", ".gitignore", ".gitattributes"}
    for name in committed:
        assert rows[name] is True
    assert set(rows) == set(vassemble.GITIGNORE) | committed


def test_readme_table_has_every_file(shop_repo):
    text = (build(shop_repo) / "README.md").read_text()
    for f, *_ in readme.FILES:
        assert f"`{f}`" in text


def test_readme_overwrites(shop_repo):
    out = build(shop_repo)
    (out / "README.md").write_text("hand edit")
    assert assemble_cli.main([str(shop_repo)]) == 0
    assert "hand edit" not in (out / "README.md").read_text()


def test_summary_starts_with_header_and_notes_are_untouched(shop_repo):
    out = build(shop_repo)
    assert (out / "summary.md").read_text().startswith(readme.header("summary.md") + "\n")
    assert not (out / "map-notes.md").exists()


def test_header_text():
    h = readme.header("audit.md")
    assert h == ("<!-- Generated by the visualizing-codebases skill (assemble.py, audit.py); "
                 "drawing and content checks, findings. Do not edit: the next run overwrites it. -->")
